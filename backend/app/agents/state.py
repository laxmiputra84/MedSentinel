"""
MedSentinel Agentic Architecture — State Models
Typed Pydantic v2 models representing WorkflowState, AgentExecutionLog,
ClinicalFinding, VerificationResult, FinalReport, and AuditTrail.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, ConfigDict


class WorkflowStatus(str, Enum):
    PENDING = "PENDING"
    IN_PROGRESS = "IN_PROGRESS"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    ESCALATED = "ESCALATED"
    DOCTOR_REVIEW_REQUIRED = "DOCTOR_REVIEW_REQUIRED"


class WorkflowType(str, Enum):
    LAB_REPORT = "LAB_REPORT"
    PRESCRIPTION = "PRESCRIPTION"
    INSURANCE_CLAIM = "INSURANCE_CLAIM"
    CLINICAL_SUMMARY = "CLINICAL_SUMMARY"
    APPOINTMENT = "APPOINTMENT"
    PATIENT_PROFILE = "PATIENT_PROFILE"
    GENERAL_INQUIRY = "GENERAL_INQUIRY"
    AUTOMATIC = "AUTOMATIC"


class AgentStatus(str, Enum):
    IDLE = "IDLE"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


class RiskLevel(str, Enum):
    LOW = "LOW"
    MODERATE = "MODERATE"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class VerificationStatus(str, Enum):
    VERIFIED = "VERIFIED"
    FLAGGED = "FLAGGED"
    PENDING = "PENDING"
    REJECTED = "REJECTED"
    INCONCLUSIVE = "INCONCLUSIVE"


class EscalationLevel(str, Enum):
    NONE = "NONE"
    MILD = "MILD"
    MODERATE = "MODERATE"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"
    DOCTOR_REVIEW_REQUIRED = "DOCTOR_REVIEW_REQUIRED"


class AgentExecutionLog(BaseModel):
    """Execution telemetry and audit log for a single agent step."""
    model_config = ConfigDict(extra="ignore")

    agent_name: str
    status: AgentStatus = AgentStatus.RUNNING
    started_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    completed_at: Optional[datetime] = None
    duration_ms: Optional[float] = None
    tool_called: Optional[str] = None
    inputs_summary: Optional[Dict[str, Any]] = Field(default_factory=dict)
    outputs_summary: Optional[Dict[str, Any]] = Field(default_factory=dict)
    error_message: Optional[str] = None
    confidence: Optional[float] = None


class ClinicalFinding(BaseModel):
    """Structured clinical or diagnostic finding with source evidence."""
    model_config = ConfigDict(extra="ignore")

    category: str = "GENERAL"  # HEMATOLOGY, BIOCHEMISTRY, PHARMACOLOGY, CLAIMS, etc.
    title: str
    description: str
    parameter_name: Optional[str] = None
    observed_value: Optional[float] = None
    reference_range: Optional[str] = None
    unit: Optional[str] = None
    status: str = "NORMAL"  # NORMAL, LOW, HIGH, CRITICAL, UNKNOWN
    is_critical: bool = False
    evidence: Optional[str] = None
    confidence: float = 0.90


class LabFinding(BaseModel):
    """Structured laboratory result item."""
    model_config = ConfigDict(extra="ignore")

    test_name: str
    observed_value: float
    unit: str
    reference_min: Optional[float] = None
    reference_max: Optional[float] = None
    status: str = "NORMAL"
    is_critical: bool = False
    historical_trend: Optional[str] = None  # STABLE, INCREASING, DECREASING, UNKNOWN
    delta_percent: Optional[float] = None
    evidence: Optional[str] = None


class VerificationResult(BaseModel):
    """Result of cryptographic and semantic verification."""
    model_config = ConfigDict(extra="ignore")

    is_valid: bool = True
    file_hash: Optional[str] = None
    stored_hash: Optional[str] = None
    document_code: Optional[str] = None
    tamper_free: bool = True
    is_duplicate: bool = False
    duplicate_of_id: Optional[int] = None
    contradiction_flags: List[str] = Field(default_factory=list)
    confidence: float = 0.95
    verification_notes: Optional[str] = None


class FinalReport(BaseModel):
    """Comprehensive, structured final healthcare decision-support report."""
    model_config = ConfigDict(extra="ignore")

    workflow_id: str
    patient_id: Optional[int] = None
    patient_name: Optional[str] = None
    document_id: Optional[int] = None
    document_type: str = "Unknown"
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    executive_summary: str
    findings: List[ClinicalFinding] = Field(default_factory=list)
    lab_summary: Optional[Dict[str, Any]] = None
    risk_assessment: Optional[Dict[str, Any]] = None
    recommendations: List[str] = Field(default_factory=list)
    citations: List[Dict[str, Any]] = Field(default_factory=list)
    disclaimer: str = (
        "IMPORTANT MEDICAL DISCLAIMER: This report is generated by MedSentinel AI for clinical "
        "decision-support and informational purposes only. It does not constitute a definitive "
        "medical diagnosis or prescription. All clinical actions must be confirmed by a licensed "
        "medical professional."
    )
    requires_human_review: bool = False
    escalation_reason: Optional[str] = None
    escalation_level: EscalationLevel = EscalationLevel.NONE
    doctor_review_notes: Optional[str] = None
    reviewer_id: Optional[int] = None
    review_status: Optional[str] = None  # PENDING, APPROVED, MODIFIED, REJECTED


class AuditEntry(BaseModel):
    """Single chronological audit trail event."""
    model_config = ConfigDict(extra="ignore")

    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    agent_name: str
    action: str
    tool_used: Optional[str] = None
    status: str = "SUCCESS"
    confidence: Optional[float] = None
    error: Optional[str] = None
    details: Dict[str, Any] = Field(default_factory=dict)


class AgentResult(BaseModel):
    """Standard return object for every agent step."""
    model_config = ConfigDict(extra="ignore")

    success: bool = True
    agent_name: str
    data: Dict[str, Any] = Field(default_factory=dict)
    findings: List[ClinicalFinding] = Field(default_factory=list)
    next_agents: List[str] = Field(default_factory=list)
    errors: List[str] = Field(default_factory=list)
    audit_entries: List[AuditEntry] = Field(default_factory=list)
    execution_log: Optional[AgentExecutionLog] = None


class WorkflowState(BaseModel):
    """
    Central state object passed between agents during workflow execution.
    Maintains all intermediate results, logs, findings, and audit trails.
    """
    model_config = ConfigDict(extra="allow")

    # Workflow Identifiers & Context
    workflow_id: str
    patient_id: Optional[int] = None
    patient_name: Optional[str] = None
    patient_demographics: Optional[Dict[str, Any]] = None
    user_id: Optional[int] = None
    user_role: str = "USER"
    document_id: Optional[int] = None
    document_code: Optional[str] = None
    hospital_id: Optional[int] = None
    file_path: Optional[str] = None
    filename: Optional[str] = None
    workflow_type: WorkflowType = WorkflowType.AUTOMATIC
    status: WorkflowStatus = WorkflowStatus.PENDING

    # Workflow Progress
    current_agent: Optional[str] = None
    completed_agents: List[str] = Field(default_factory=list)
    skipped_agents: List[str] = Field(default_factory=list)
    failed_agents: List[str] = Field(default_factory=list)

    # Document & OCR Layer
    document_type: Optional[str] = None
    document_confidence: Optional[float] = None
    extracted_text: Optional[str] = None
    extracted_entities: Dict[str, Any] = Field(default_factory=dict)
    document_metadata: Dict[str, Any] = Field(default_factory=dict)

    # Clinical & Validation Layer
    validation_status: Dict[str, Any] = Field(default_factory=dict)
    validation_errors: List[str] = Field(default_factory=list)
    validation_warnings: List[str] = Field(default_factory=list)
    lab_results: List[Dict[str, Any]] = Field(default_factory=list)
    historical_results: List[Dict[str, Any]] = Field(default_factory=list)
    longitudinal_trends: Dict[str, Any] = Field(default_factory=dict)
    clinical_findings: List[ClinicalFinding] = Field(default_factory=list)

    # Knowledge & Risk Layer
    retrieved_evidence: List[Dict[str, Any]] = Field(default_factory=list)
    rag_context: Optional[str] = None
    risk_result: Optional[Dict[str, Any]] = None
    fraud_result: Optional[Dict[str, Any]] = None

    # Verification & Escalation Layer
    verification_result: Optional[VerificationResult] = None
    escalation_required: bool = False
    escalation_reason: Optional[str] = None
    escalation_level: EscalationLevel = EscalationLevel.NONE

    # Final Outputs
    final_report: Optional[FinalReport] = None
    execution_logs: List[AgentExecutionLog] = Field(default_factory=list)
    audit_trail: List[AuditEntry] = Field(default_factory=list)

    # Timestamps
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    def add_execution_log(self, log: AgentExecutionLog) -> None:
        """Appends or updates an agent execution log."""
        self.execution_logs.append(log)
        self.updated_at = datetime.now(timezone.utc)

    def add_audit_entry(
        self,
        agent_name: str,
        action: str,
        tool_used: Optional[str] = None,
        status: str = "SUCCESS",
        confidence: Optional[float] = None,
        error: Optional[str] = None,
        details: Optional[Dict[str, Any]] = None,
    ) -> None:
        """Records an audit event in the state."""
        entry = AuditEntry(
            agent_name=agent_name,
            action=action,
            tool_used=tool_used,
            status=status,
            confidence=confidence,
            error=error,
            details=details or {},
        )
        self.audit_trail.append(entry)
        self.updated_at = datetime.now(timezone.utc)

    def add_clinical_finding(self, finding: ClinicalFinding) -> None:
        """Adds a structured clinical finding and checks for critical panic values."""
        self.clinical_findings.append(finding)
        if finding.is_critical:
            self.escalation_required = True
            self.escalation_level = EscalationLevel.DOCTOR_REVIEW_REQUIRED
            if not self.escalation_reason:
                self.escalation_reason = f"Critical laboratory parameter detected: {finding.title}"
        self.updated_at = datetime.now(timezone.utc)

    def mark_agent_completed(self, agent_name: str) -> None:
        """Marks agent as successfully finished."""
        if agent_name not in self.completed_agents:
            self.completed_agents.append(agent_name)
        self.updated_at = datetime.now(timezone.utc)

    def mark_agent_failed(self, agent_name: str) -> None:
        """Marks agent as failed."""
        if agent_name not in self.failed_agents:
            self.failed_agents.append(agent_name)
        self.updated_at = datetime.now(timezone.utc)

    def mark_agent_skipped(self, agent_name: str) -> None:
        """Marks agent as skipped due to conditional DAG routing."""
        if agent_name not in self.skipped_agents:
            self.skipped_agents.append(agent_name)
        self.updated_at = datetime.now(timezone.utc)
